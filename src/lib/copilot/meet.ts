import "server-only"
import { googleApiFetch } from "./googleAuth"
import { createCalendarEvent } from "./calendar"
import { sendGmail } from "./gmail"

export interface InstantMeetOptions {
  topic?: string
}

export interface ScheduleMeetOptions {
  topic: string
  description?: string
  startTime: string // ISO string (e.g. 2026-11-04T10:00:00+06:00)
  endTime: string   // ISO string (e.g. 2026-11-04T11:00:00+06:00)
  attendees?: string[] // list of emails
  sendEmailInvites?: boolean
}

/**
 * Creates an instant Google Meet space using Google Meet REST API v2
 * (with automatic fallback to Google Calendar Conference Meet generation).
 */
export async function createInstantMeetSpace(userId: string, opts: InstantMeetOptions = {}) {
  const topic = opts.topic || "noBrain Meeting"

  // 1. Try Google Meet REST API v2 directly
  try {
    const res = await googleApiFetch(userId, "https://meet.googleapis.com/v2/spaces", {
      method: "POST",
      headers: { "Content-Type": "application/json" },
      body: JSON.stringify({
        config: {
          accessType: "OPEN",
        },
      }),
    })

    if (res.ok) {
      const data = await res.json()
      if (data.meetingUri) {
        return {
          success: true,
          meetingUri: data.meetingUri,
          meetingCode: data.meetingCode || data.meetingUri.split("/").pop(),
          spaceName: data.name,
          topic,
          createdAt: new Date().toISOString(),
        }
      }
    }
  } catch (err: any) {
    console.warn("Meet REST API v2 failed, falling back to Calendar Meet conference:", err.message)
  }

  // 2. Reliable Fallback via Calendar Meet API
  const now = new Date()
  const oneHourLater = new Date(now.getTime() + 60 * 60 * 1000)

  const calEvent = await createCalendarEvent(userId, {
    summary: topic,
    description: `Instant meeting generated by noBrain Copilot at ${now.toLocaleTimeString()}`,
    start: now.toISOString(),
    end: oneHourLater.toISOString(),
    createMeetLink: true,
  })

  if (!calEvent.meetLink) {
    throw new Error("Could not generate Google Meet link. Please ensure Google Calendar & Meet are enabled.")
  }

  return {
    success: true,
    meetingUri: calEvent.meetLink,
    meetingCode: calEvent.meetLink.split("/").pop() || "",
    calendarEventId: calEvent.id,
    topic,
    createdAt: now.toISOString(),
  }
}

/**
 * Schedules a Google Meet meeting, automatically adds it to Google Calendar,
 * and optionally dispatches formatted invitation emails to attendees via Gmail.
 */
export async function scheduleMeetingWithCalendar(userId: string, opts: ScheduleMeetOptions) {
  // 1. Create event with Google Meet link in Calendar
  const calEvent = await createCalendarEvent(userId, {
    summary: opts.topic,
    description: opts.description || "",
    start: opts.startTime,
    end: opts.endTime,
    attendees: opts.attendees,
    createMeetLink: true,
  })

  const meetLink = calEvent.meetLink || ""

  // 2. If attendees provided and sendEmailInvites is true, send Gmail invitations
  let emailsSent = 0
  if (opts.sendEmailInvites && opts.attendees && opts.attendees.length > 0 && meetLink) {
    const formattedDate = new Date(opts.startTime).toLocaleString("en-US", {
      dateStyle: "full",
      timeStyle: "short",
    })

    for (const recipient of opts.attendees) {
      try {
        await sendGmail(userId, {
          to: recipient,
          subject: `Meeting Invitation: ${opts.topic}`,
          body: `Hi,\n\nYou have been invited to a meeting:\n\nTopic: ${opts.topic}\nTime: ${formattedDate}\n\nJoin Google Meet:\n${meetLink}\n\n${opts.description ? `Agenda:\n${opts.description}\n\n` : ""}Best regards,\nnoBrain Copilot`,
        })
        emailsSent++
      } catch (e: any) {
        console.warn(`Failed to email invite to ${recipient}:`, e.message)
      }
    }
  }

  return {
    success: true,
    topic: opts.topic,
    startTime: calEvent.start,
    endTime: calEvent.end,
    meetLink,
    calendarEventId: calEvent.id,
    calendarHtmlLink: calEvent.htmlLink,
    attendees: opts.attendees || [],
    emailInvitesSent: emailsSent,
  }
}

